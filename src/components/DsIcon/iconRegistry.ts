export function toPascalCase(str: string): string {
  return str
    .replace(/(^\w|[_\s-]\w)/g, (clear) => clear.replace(/[_\s-]/, '').toUpperCase())
    .trim()
}

/**
 * Registers custom or additional Lucide icons for string-based lookup in `<DsIcon>`
 * without requiring a full `import * as LucideIcons` namespace bundle (DS-12, PKG-01).
 */
export function registerDsIcons(icons: Record<string, Component>): void {
  for (const [key, comp] of Object.entries(icons)) {
    const pascal = toPascalCase(key)
    iconMap[pascal] = comp
    iconMap[key] = comp
  }
}

export function resolveIconByName(name: string): Component | undefined {
  const trimmed = name.trim()
  if (!trimmed) return undefined
  const pascal = toPascalCase(trimmed)
  return iconMap[pascal] || iconMap[trimmed] || iconMap[`${pascal}Icon`]
}
